// --- Language Switching Logic ---
let currentLang = localStorage.getItem('lang') || 'tr';

function changeLanguage(lang) {
    if (translations[lang]) {
        currentLang = lang;
        localStorage.setItem('lang', lang);

        const langBtn = document.getElementById('currentLang');
        if (langBtn) {
            langBtn.innerHTML = `${lang.toUpperCase()} <i class="fa-solid fa-globe"></i>`;
        }

        document.documentElement.setAttribute('dir', lang === 'ar' ? 'rtl' : 'ltr');
        document.documentElement.lang = lang;

        const elements = document.querySelectorAll('[data-i18n]');
        elements.forEach(el => {
            const key = el.getAttribute('data-i18n');
            const translation = (translations[lang] && translations[lang][key]) || (translations['en'] && translations['en'][key]) || (translations['tr'] && translations['tr'][key]);

            if (translation) {
                if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
                    el.placeholder = translation;
                } else {
                    el.innerHTML = translation;
                }
            }
        });

        if (typeof renderFAQs === 'function') renderFAQs(lang);
    }

    // Google Translate Logic
    const triggerGoogleTranslate = (langCode) => {
        const select = document.querySelector('select.goog-te-combo');
        if (select) {
            select.value = langCode;
            select.dispatchEvent(new Event('change'));
        }
    };

    if (lang !== 'tr') {
        triggerGoogleTranslate(lang);
    } else {
        const select = document.querySelector('select.goog-te-combo');
        if (select) {
            select.value = '';
            select.dispatchEvent(new Event('change'));
        }
    }
}

document.addEventListener('DOMContentLoaded', () => {
    // Initial language application
    changeLanguage(currentLang);
});

// --- Theme Toggle ---
const themeToggleBtn = document.getElementById('themeToggle');
const body = document.documentElement;

function updateLogo() {
    const navLogo = document.getElementById('navLogo');
    const footerLogo = document.getElementById('footerLogo');
    const isDark = body.getAttribute('data-theme') === 'dark';

    if (navLogo) {
        navLogo.src = isDark ? 'beyazLogo.png' : 'siyahLogo.png';
    }
    if (footerLogo) {
        footerLogo.src = isDark ? 'beyazLogo.png' : 'siyahLogo.png';
    }
}

themeToggleBtn?.addEventListener('click', () => {
    const isDark = body.getAttribute('data-theme') === 'dark';
    if (isDark) {
        body.removeAttribute('data-theme');
        themeToggleBtn.innerHTML = '<i class="fa-solid fa-moon"></i>';
        localStorage.setItem('theme', 'light');
    } else {
        body.setAttribute('data-theme', 'dark');
        themeToggleBtn.innerHTML = '<i class="fa-solid fa-sun"></i>';
        localStorage.setItem('theme', 'dark');
    }
    updateLogo();
});

if (localStorage.getItem('theme') === 'dark') {
    body.setAttribute('data-theme', 'dark');
    if (themeToggleBtn) themeToggleBtn.innerHTML = '<i class="fa-solid fa-sun"></i>';
}
updateLogo();

// --- Navbar Scroll Logic ---
let lastScroll = 0;
const navbar = document.querySelector('.navbar');

window.addEventListener('scroll', () => {
    const currentScroll = window.pageYOffset;
    if (currentScroll <= 0) {
        navbar?.classList.remove('navbar--hidden');
        return;
    }
    if (currentScroll > lastScroll && !navbar?.classList.contains('navbar--hidden')) {
        navbar?.classList.add('navbar--hidden');
    } else if (currentScroll < lastScroll && navbar?.classList.contains('navbar--hidden')) {
        navbar?.classList.remove('navbar--hidden');
    }
    lastScroll = currentScroll;
});

// --- Mobile Nav ---
const mobileToggle = document.getElementById('mobileToggle');
const navLinksMenu = document.querySelector('.navbar .nav-links'); // Specific selector
mobileToggle?.addEventListener('click', (e) => {
    e.stopPropagation();
    navLinksMenu?.classList.toggle('active');
});

// Close mobile menu when clicking outside
document.addEventListener('click', (e) => {
    if (navLinksMenu?.classList.contains('active') && !navLinksMenu.contains(e.target) && e.target !== mobileToggle) {
        navLinksMenu.classList.remove('active');
    }
});

// FAQ Rendering
function renderFAQs(lang) {
    const faqContainer = document.getElementById('faqAccordion');
    if (!faqContainer || typeof faqData === 'undefined') return;

    faqContainer.innerHTML = '';
    const questions = faqData[lang] || faqData['en'] || faqData['tr'];

    questions.forEach((item) => {
        const accordionItem = document.createElement('div');
        accordionItem.className = 'accordion-item';
        accordionItem.innerHTML = `
            <button class="accordion-header">
                <span>${item.q}</span>
                <i class="fa-solid fa-chevron-down"></i>
            </button>
            <div class="accordion-content">
                <p>${item.a}</p>
            </div>
        `;
        const header = accordionItem.querySelector('.accordion-header');
        header.addEventListener('click', () => {
            const isActive = accordionItem.classList.contains('active');
            document.querySelectorAll('.accordion-item').forEach(i => i.classList.remove('active'));
            if (!isActive) accordionItem.classList.add('active');
        });
        faqContainer.appendChild(accordionItem);
    });
}

// Process Modal Logic
function openProcessModal(step) {
    const modal = document.getElementById('processModal');
    const title = document.getElementById('modalTitle');
    const desc = document.getElementById('modalDescription');
    const lang = document.documentElement.lang || 'tr';
    
    // Fallback logic for translations
    const getTranslation = (key) => {
        return (translations[lang] && translations[lang][key]) || 
               (translations['en'] && translations['en'][key]) || 
               (translations['tr'] && translations['tr'][key]) || 
               "";
    };
    
    title.innerText = getTranslation('proc' + step + 'Title');
    desc.innerText = getTranslation('proc' + step + 'Desc');
    
    modal.style.display = 'block';
    document.body.style.overflow = 'hidden'; 
}

function closeProcessModal() {
    const modal = document.getElementById('processModal');
    modal.style.display = 'none';
    document.body.style.overflow = 'auto';
}

window.onclick = function(event) {
    const modal = document.getElementById('processModal');
    if (event.target == modal) {
        closeProcessModal();
    }
}
